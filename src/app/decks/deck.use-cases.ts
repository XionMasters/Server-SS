import { DeckService } from './deck.service';

export const deckUseCases = {
  getUserDecks: (userId: string) => DeckService.getUserDecks(userId),
  getDeck: (userId: string, deckId: string) => DeckService.getDeckByIdForUser(userId, deckId),
  createDeck: (userId: string, name: string, description?: string) =>
    DeckService.createDeckForUser(userId, name, description),
  updateDeck: (
    userId: string,
    deckId: string,
    data: { name?: string; description?: string; is_active?: boolean }
  ) => DeckService.updateDeckForUser(userId, deckId, data),
  deleteDeck: (userId: string, deckId: string) => DeckService.deleteDeckForUser(userId, deckId),
  addCard: (userId: string, deckId: string, cardId: string, quantity?: number) =>
    DeckService.addCardToDeck(userId, deckId, cardId, quantity),
  removeCard: (userId: string, deckId: string, cardId: string) =>
    DeckService.removeCardFromDeck(userId, deckId, cardId),
  updateCardQuantity: (userId: string, deckId: string, cardId: string, quantity: number) =>
    DeckService.updateCardQuantity(userId, deckId, cardId, quantity),
  syncCards: (
    userId: string,
    deckId: string,
    cards: Array<{ card_id: string; quantity: number }>
  ) => DeckService.syncDeckCards(userId, deckId, cards),
  validateDeck: (userId: string, deckId: string) =>
    DeckService.validateDeckForUser(userId, deckId),
  getStatistics: (userId: string, deckId: string) =>
    DeckService.getDeckStatisticsForUser(userId, deckId),
  autoGenerate: (userId: string, deckId: string, options: Record<string, unknown>) =>
    DeckService.autoGenerateDeckForUser(userId, deckId, options),
  setCoverCard: (userId: string, deckId: string, cardId: string | null) =>
    DeckService.setDeckCoverCard(userId, deckId, cardId),
  getExpandedCards: (userId: string, deckId: string) =>
    DeckService.getDeckCardsExpandedForUser(userId, deckId),
};
