export const autoGenerateDeck = async (req: Request, res: Response): Promise<void> => {
  try {
    const response = await deckUseCases.autoGenerate(
      getUserId(req),
      req.params.id,
      req.body || {}
    );
    res.json(response);
  } catch (error: any) {
    if (error instanceof ServiceError) {
      res.status(error.status).json({ error: error.message });
      return;
    }

    console.error('Error generando deck automáticamente', error);
    res.status(500).json({
      error: error?.message || 'Error generando deck automáticamente',
    });
  }
};

