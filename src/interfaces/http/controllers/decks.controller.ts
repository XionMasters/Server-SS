import { Request, Response } from 'express';
import { deckUseCases } from '../../../app/decks/deck.use-cases';
import { ServiceError } from '../../../app/decks/deck.service';

function getUserId(req: Request): string {
  return (req as any).user.id;
}

function handleError(res: Response, error: unknown, fallbackMessage: string): void {
  if (error instanceof ServiceError) {
    res.status(error.status).json({ error: error.message });
    return;
  }

  console.error(fallbackMessage, error);
  res.status(500).json({ error: fallbackMessage });
}

async function execute(
  res: Response,
  operation: () => Promise<unknown>,
  fallbackMessage: string,
  status = 200
): Promise<void> {
  try {
    res.status(status).json(await operation());
  } catch (error) {
    handleError(res, error, fallbackMessage);
  }
}

export const getUserDecks = (req: Request, res: Response): Promise<void> =>
  execute(res, () => deckUseCases.getUserDecks(getUserId(req)), 'Error obteniendo decks del usuario');

export const getDeck = (req: Request, res: Response): Promise<void> =>
  execute(res, () => deckUseCases.getDeck(getUserId(req), req.params.id), 'Error obteniendo deck');

export const createDeck = (req: Request, res: Response): Promise<void> =>
  execute(
    res,
    () => deckUseCases.createDeck(getUserId(req), req.body.name, req.body.description),
    'Error creando deck',
    201
  );

export const updateDeck = (req: Request, res: Response): Promise<void> =>
  execute(
    res,
    () => deckUseCases.updateDeck(getUserId(req), req.params.id, {
      name: req.body.name,
      description: req.body.description,
      is_active: req.body.is_active,
    }),
    'Error actualizando deck'
  );

export const deleteDeck = async (req: Request, res: Response): Promise<void> => {
  try {
    await deckUseCases.deleteDeck(getUserId(req), req.params.id);
    res.json({ message: 'Deck eliminado exitosamente' });
  } catch (error) {
    handleError(res, error, 'Error eliminando deck');
  }
};

export const addCardToDeck = async (req: Request, res: Response): Promise<void> => {
  try {
    const result = await deckUseCases.addCard(
      getUserId(req),
      req.params.id,
      req.body.card_id,
      req.body.quantity ?? 1
    );
    res.status(result.created ? 201 : 200).json(result.deckCard);
  } catch (error) {
    handleError(res, error, 'Error agregando carta al deck');
  }
};

export const removeCardFromDeck = async (req: Request, res: Response): Promise<void> => {
  try {
    await deckUseCases.removeCard(getUserId(req), req.params.id, req.params.card_id);
    res.json({ message: 'Carta removida del deck exitosamente' });
  } catch (error) {
    handleError(res, error, 'Error removiendo carta del deck');
  }
};

